-- Esquema académico Oracle 12c+. No ejecutar sobre tablas de la versión anterior.
-- El gerente y su departamento se insertan en una transacción con FK diferida.
CREATE TABLE DEPARTAMENTO (
    ID_DEPARTAMENTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE VARCHAR2(150 CHAR) NOT NULL,
    ID_GERENTE NUMBER NOT NULL,
    CONSTRAINT PK_DEPARTAMENTO PRIMARY KEY (ID_DEPARTAMENTO)
);
CREATE TABLE EMPLEADO (
    ID_EMPLEADO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DATOS_CIFRADOS CLOB NOT NULL,
    TIPO_EMPLEADO VARCHAR2(30 CHAR) NOT NULL,
    ID_DEPARTAMENTO NUMBER NOT NULL,
    CONSTRAINT PK_EMPLEADO PRIMARY KEY (ID_EMPLEADO),
    CONSTRAINT CK_EMPLEADO_TIPO CHECK (TIPO_EMPLEADO IN ('GERENTE','RECURSOS_HUMANOS','VENDEDOR')),
    CONSTRAINT FK_EMPLEADO_DEPARTAMENTO FOREIGN KEY (ID_DEPARTAMENTO)
        REFERENCES DEPARTAMENTO(ID_DEPARTAMENTO) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE PROYECTO (
    ID_PROYECTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE VARCHAR2(150 CHAR) NOT NULL,
    DESCRIPCION VARCHAR2(1000 CHAR) NOT NULL,
    FECHA_INICIO DATE NOT NULL,
    CONSTRAINT PK_PROYECTO PRIMARY KEY (ID_PROYECTO)
);
CREATE TABLE ASIGNACION (
    ID_ASIGNACION NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_EMPLEADO NUMBER NOT NULL,
    ID_PROYECTO NUMBER NOT NULL,
    ACTIVA CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_ASIGNACION PRIMARY KEY (ID_ASIGNACION),
    CONSTRAINT UQ_ASIGNACION_PAR UNIQUE (ID_EMPLEADO, ID_PROYECTO),
    CONSTRAINT CK_ASIGNACION_ACTIVA CHECK (ACTIVA IN ('S','N')),
    CONSTRAINT FK_ASIGNACION_EMPLEADO FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADO(ID_EMPLEADO),
    CONSTRAINT FK_ASIGNACION_PROYECTO FOREIGN KEY (ID_PROYECTO) REFERENCES PROYECTO(ID_PROYECTO)
);
CREATE TABLE TRABAJO_REALIZADO (
    ID_TRABAJO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_EMPLEADO NUMBER NOT NULL,
    ID_PROYECTO NUMBER NOT NULL,
    FECHA DATE NOT NULL,
    HORAS NUMBER(4,2) NOT NULL,
    DESCRIPCION VARCHAR2(1000 CHAR) NOT NULL,
    CONSTRAINT PK_TRABAJO PRIMARY KEY (ID_TRABAJO),
    CONSTRAINT CK_TRABAJO_HORAS CHECK (HORAS > 0 AND HORAS <= 24),
    CONSTRAINT FK_TRABAJO_ASIGNACION FOREIGN KEY (ID_EMPLEADO, ID_PROYECTO)
        REFERENCES ASIGNACION(ID_EMPLEADO, ID_PROYECTO)
);
CREATE TABLE USUARIO (
    ID_USUARIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_USUARIO VARCHAR2(50 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(512 CHAR) NOT NULL,
    ID_EMPLEADO NUMBER NOT NULL,
    ACTIVO CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    ROL VARCHAR2(10 CHAR) DEFAULT 'EMPLEADO' NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIO_NOMBRE UNIQUE (NOMBRE_USUARIO),
    CONSTRAINT UQ_USUARIO_EMPLEADO UNIQUE (ID_EMPLEADO),
    CONSTRAINT FK_USUARIO_EMPLEADO FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADO(ID_EMPLEADO),
    CONSTRAINT CK_USUARIO_ACTIVO CHECK (ACTIVO IN ('S','N')),
    CONSTRAINT CK_USUARIO_ROL CHECK (ROL IN ('ADMIN','EMPLEADO'))
);
ALTER TABLE DEPARTAMENTO ADD CONSTRAINT FK_DEPARTAMENTO_GERENTE
    FOREIGN KEY (ID_GERENTE) REFERENCES EMPLEADO(ID_EMPLEADO) DEFERRABLE INITIALLY DEFERRED;
CREATE INDEX IX_EMPLEADO_DEPARTAMENTO ON EMPLEADO(ID_DEPARTAMENTO);
CREATE INDEX IX_DEPARTAMENTO_GERENTE ON DEPARTAMENTO(ID_GERENTE);
CREATE INDEX IX_ASIGNACION_PROYECTO ON ASIGNACION(ID_PROYECTO);
CREATE INDEX IX_TRABAJO_EMPLEADO ON TRABAJO_REALIZADO(ID_EMPLEADO);
CREATE INDEX IX_TRABAJO_PROYECTO ON TRABAJO_REALIZADO(ID_PROYECTO);
