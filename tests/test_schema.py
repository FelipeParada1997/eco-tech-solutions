"""Instalación inicial, repetición y recuperación sin eliminar datos existentes."""
import re
from unittest.mock import Mock

import pytest

from ecotech.database.schema import TABLE_COLUMNS, instalar, statements
from ecotech.scripts.crear_tablas import main


class OracleSchema:
    def __init__(self):
        self.objects = set()
        self.columns = set()
        self.constraints = set()
        self.departments = []
        self.executed = []
        self.rows = []
        self.fail_on = None
        self.closed = False
        self.connection = Mock()
        self.connection.cursor.return_value = self

    def execute(self, sql, params=None):
        self.executed.append(sql)
        if self.fail_on and self.fail_on in sql:
            raise RuntimeError("interrupción simulada")
        if sql == "SELECT object_name, object_type FROM user_objects":
            self.rows = list(self.objects)
        elif sql == "SELECT table_name, column_name FROM user_tab_columns":
            self.rows = list(self.columns)
        elif sql == "SELECT constraint_name FROM user_constraints":
            self.rows = [(n,) for n in self.constraints]
        elif sql.startswith("SELECT COUNT(*)"):
            self.rows = [(len(self.departments),)]
        elif sql.startswith("SELECT ID_DEPARTAMENTO"):
            self.rows = list(self.departments)
        elif sql.startswith("INSERT INTO DEPARTAMENTO"):
            self.departments.append((1, params["nombre"]))
        elif sql.startswith("CREATE TABLE"):
            name = sql.split()[2]
            self.objects.add((name, "TABLE"))
            self.columns.update((name, col) for col in TABLE_COLUMNS[name])
            self.constraints.update(re.findall(r"CONSTRAINT (\w+)", sql))
        elif sql.startswith("CREATE INDEX"):
            self.objects.add((sql.split()[2], "INDEX"))
        elif sql.startswith("ALTER TABLE"):
            self.constraints.add(re.search(r"ADD CONSTRAINT (\w+)", sql).group(1))
        else:
            raise AssertionError(sql)

    def fetchall(self):
        return self.rows

    def fetchone(self):
        return self.rows[0]

    def close(self):
        self.closed = True


def test_initial_setup_then_rerun_preserves_data_and_ids():
    oracle = OracleSchema()
    created, departments = instalar(lambda: oracle.connection)
    assert len(created) == 12  # seis tablas, cinco índices, una FK circular
    assert departments == []
    assert {name for name, kind in oracle.objects if kind == "TABLE"} == set(TABLE_COLUMNS)
    assert "FK_DEPARTAMENTO_GERENTE" in oracle.constraints
    oracle.departments.append((9, "Departamento existente"))
    again, departments = instalar(lambda: oracle.connection)
    assert again == []
    assert departments == [(9, "Departamento existente")]
    assert sum(sql.startswith("INSERT INTO DEPARTAMENTO") for sql in oracle.executed) == 0
    assert oracle.closed
    assert oracle.connection.close.call_count == 2


def test_incompatible_existing_table_stops_before_any_ddl():
    oracle = OracleSchema()
    oracle.objects.add(("EMPLEADO", "TABLE"))
    oracle.columns.add(("EMPLEADO", "ID_EMPLEADO"))
    with pytest.raises(ValueError, match="EMPLEADO no es compatible"):
        instalar(lambda: oracle.connection)
    assert not any(sql.startswith(("CREATE ", "ALTER ", "INSERT ")) for sql in oracle.executed)
    oracle.connection.rollback.assert_called_once()
    oracle.connection.close.assert_called_once()


def test_interrupted_ddl_can_resume_without_recreating_tables():
    oracle = OracleSchema()
    oracle.fail_on = "CREATE TABLE PROYECTO"
    with pytest.raises(RuntimeError):
        instalar(lambda: oracle.connection)
    assert ("EMPLEADO", "TABLE") in oracle.objects
    oracle.fail_on = None
    created, _ = instalar(lambda: oracle.connection)
    assert "PROYECTO" in created and "EMPLEADO" not in created
    assert len(oracle.departments) == 0


def test_ddl_contains_repository_columns_generated_ids_and_no_destructive_statements():
    sql = "\n".join(statements())
    assert not re.search(r"\b(DROP|TRUNCATE|DELETE)\b", sql)
    for table, columns in TABLE_COLUMNS.items():
        statement = next(s for s in statements() if s.startswith(f"CREATE TABLE {table} ("))
        for column in columns:
            assert re.search(rf"\b{column}\b", statement)
        assert "GENERATED BY DEFAULT ON NULL AS IDENTITY" in statement
    assert "ID_GERENTE NUMBER NOT NULL" in sql
    assert "UNIQUE (NOMBRE_USUARIO)" in sql


def test_cli_explains_invalid_oracle_credentials(monkeypatch, capsys):
    import oracledb
    import ecotech.scripts.crear_tablas as cli
    error = Mock(code=1017)
    monkeypatch.setattr(cli, "instalar", Mock(side_effect=oracledb.DatabaseError(error)))
    assert main() == 1
    output = capsys.readouterr().out
    assert "ORACLE_USER/ORACLE_PASSWORD" in output
    assert "No se crearon tablas" in output


def test_missing_identity_privilege_identifies_failing_object(monkeypatch):
    import oracledb
    oracle = OracleSchema()
    execute = oracle.execute

    def fail_create(sql, params=None):
        if sql.startswith("CREATE TABLE"):
            raise oracledb.DatabaseError(Mock(code=1031))
        execute(sql, params)

    monkeypatch.setattr(oracle, "execute", fail_create)
    with pytest.raises(ValueError, match="TABLE DEPARTAMENTO.*ORA-01031.*CREATE SEQUENCE"):
        instalar(lambda: oracle.connection)
    oracle.connection.rollback.assert_called_once()
    oracle.connection.close.assert_called_once()
